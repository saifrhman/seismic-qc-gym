"""Collect results/*.json into results/baselines.md (the tables quoted in the README).

    python scripts/summarise_results.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ORDER = ["oracle", "heuristic", "llm", "noop", "flag_all", "kill_all"]


def main() -> None:
    rows = []
    per_type = {}
    for f in sorted((ROOT / "results").glob("*.json")):
        agent, split = f.stem.rsplit("_", 1)
        s = json.loads(f.read_text())["summary"]
        rows.append((agent, split, s))
        per_type[(agent, split)] = s["per_type"]
    key = lambda r: (ORDER.index(r[0].split("_")[0]) if r[0].split("_")[0] in ORDER else 99, r[0], r[1] != "val")  # noqa: E731
    rows.sort(key=key)
    lines = [
        "# Baseline results",
        "",
        "Generated by `scripts/summarise_results.py` from `results/*.json`. Each split has the stated number of",
        "episodes (4 gathers each, difficulty cycling easy/medium/hard). val uses regime A; test uses the held-out regime B.",
        "",
        "| agent | split | episodes | reward | detection F1 | precision | recall | repair | damage | tool calls |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for agent, split, s in rows:
        lines.append(
            f"| {agent} | {split} | {s['n_episodes']} | {s['reward']:+.3f} | {s['detection_f1']:.3f} | "
            f"{s['detection_precision']:.3f} | {s['detection_recall']:.3f} | {s['repair']:.3f} | {s['damage']:.3f} | "
            f"{s['tool_calls']:.1f} |"
        )
    for agent in ("heuristic", "oracle"):
        if (agent, "val") not in per_type:
            continue
        lines += ["", f"## {agent}: per defect type (recall / precision / repair)", "", "| defect type | val | test |", "|---|---|---|"]
        for dtype, v in per_type[(agent, "val")].items():
            t = per_type.get((agent, "test"), {}).get(dtype)
            fmt = lambda x: f"{x['recall']:.3f} / {x['precision']:.3f} / {x.get('repair', float('nan')):.3f}"  # noqa: E731
            lines.append(f"| {dtype} | {fmt(v)} | {fmt(t) if t else '-'} |")
    out = ROOT / "results" / "baselines.md"
    out.write_text("\n".join(lines) + "\n")
    print(out.read_text())


if __name__ == "__main__":
    main()
